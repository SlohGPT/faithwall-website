/**
 * Post-build: append a generated "All guides" section to dist/llms.txt.
 *
 * public/llms.txt stays curated; Vite copies it to dist/llms.txt. This script lists every
 * sitemap URL that the curated file does not already link (legal pages skipped), taking the
 * title and meta description from the prerendered dist HTML. Idempotent: the section sits
 * between two marker comments and is replaced on every run.
 *
 * Usage: node scripts/build-llms.mjs   (runs last in `npm run build`)
 */
import { readFileSync, writeFileSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');
const ORIGIN = 'https://faithwall.app';
const START = '<!-- build-llms:start (generated by scripts/build-llms.mjs, do not edit) -->';
const END = '<!-- build-llms:end -->';
const LEGAL = new Set(['/privacy-policy', '/terms-of-use', '/eula']);

const norm = (p) => (p.length > 1 ? p.replace(/\/+$/, '') : p) || '/';

function decode(s) {
  const named = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ' };
  return s.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (m, e) => {
    if (e[0] === '#') {
      const cp = e[1].toLowerCase() === 'x' ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10);
      return Number.isFinite(cp) ? String.fromCodePoint(cp) : m;
    }
    return e.toLowerCase() in named ? named[e.toLowerCase()] : m;
  });
}

function head(html) {
  const t = html.match(/<title[^>]*>([\s\S]*?)<\/title>/i);
  let desc = null;
  for (const m of html.matchAll(/<meta\b[^>]*>/gi)) {
    if (/\bname="description"/i.test(m[0])) {
      const c = m[0].match(/\bcontent="([^"]*)"/i);
      if (c) { desc = c[1]; break; }
    }
  }
  const clean = (s) => decode(s).replace(/\s+/g, ' ').trim();
  return { title: t ? clean(t[1]) : '', desc: desc ? clean(desc) : '' };
}

const stripBrand = (t) => t.replace(/\s*\|\s*FaithWall\s*$/i, '').replace(/\s+[—–-]\s+FaithWall\s*$/i, '').trim();
const mdText = (s) => s.replace(/([[\]])/g, '\\$1');

const llmsPath = join(dist, 'llms.txt');
if (!existsSync(llmsPath)) { console.error('build-llms: dist/llms.txt missing'); process.exit(1); }
let llms = readFileSync(llmsPath, 'utf8');

// Drop any earlier generated section so a re-run replaces it.
const a = llms.indexOf(START);
if (a !== -1) {
  const b = llms.indexOf(END, a);
  llms = (llms.slice(0, a) + (b === -1 ? '' : llms.slice(b + END.length))).replace(/\s+$/, '') + '\n';
}

const listed = new Set();
for (const m of llms.matchAll(/https?:\/\/[^\s)\]>"']+/g)) {
  try { const u = new URL(m[0]); if (u.origin === ORIGIN) listed.add(norm(u.pathname)); } catch { /* ignore */ }
}
for (const m of llms.matchAll(/\]\((\/[^)\s]*)\)/g)) listed.add(norm(m[1]));

const sitemap = readFileSync(join(dist, 'sitemap.xml'), 'utf8');
const paths = [];
for (const m of sitemap.matchAll(/<loc>\s*([^<\s]+)\s*<\/loc>/g)) {
  let p;
  try { const u = new URL(decode(m[1])); if (u.origin !== ORIGIN) continue; p = norm(u.pathname); } catch { continue; }
  if (p === '/' || LEGAL.has(p) || listed.has(p) || paths.includes(p)) continue;
  paths.push(p);
}

const guides = [];
const articles = [];
for (const p of paths) {
  const file = join(dist, p, 'index.html');
  if (!existsSync(file)) { console.error(`build-llms: no prerendered page for ${p}`); process.exit(1); }
  const { title, desc } = head(readFileSync(file, 'utf8'));
  const t = stripBrand(title);
  if (!t) { console.error(`build-llms: no <title> for ${p}`); process.exit(1); }
  const line = `- [${mdText(t)}](${ORIGIN}${p})${desc ? `: ${desc}` : ''}`;
  (p.startsWith('/blog/') ? articles : guides).push(line);
}

const out = [START, '', '## All guides', ''];
if (guides.length) out.push('### Guides', '', ...guides, '');
if (articles.length) out.push('### Articles', '', ...articles, '');
out.push(END, '');

writeFileSync(llmsPath, llms.replace(/\s+$/, '') + '\n\n' + out.join('\n'));
console.log(`build-llms: ${guides.length} guides + ${articles.length} articles appended to dist/llms.txt`);
